def main():
    text = README.read_text(encoding='utf-8')
    i = text.find(START)
    j = text.find(END)
    if i < 0 or j < 0 or j <= i:
        print(f'定位失败：start={i} end={j}')
        return 1
    old = text[i:j]
    new_text = text[:i] + NEW + text[j:]
    print(f'旧条目 {len(old)} 字符 → 新条目 {len(NEW)} 字符')
