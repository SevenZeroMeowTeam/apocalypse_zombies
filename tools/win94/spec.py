# -*- coding: utf-8 -*-
"""win94（Winchester Model 1894）建模规范 —— 唯一的数字来源。

坐标与单位（项目铁律，见 docs/wiki/05-武器制作流程.md）
------------------------------------------------------
  16 u = 1 方块；1 u = 62.5 mm；1 in = 25.4 mm = 0.4064 u
  枪口 −Z、上 +Y、+X = 射手右侧（装填门与抛壳口都在 +X 侧）
  原点 = 机匣中心（膛线轴线 bore 在 y = 0）

真枪基准
--------
取 **Winchester Model 1894 Rifle，24 英寸枪管**（.30-30/.32 同族外形；本模组按 .45-70 设定弹道）。
长度换算以机匣长 7.2 in 为标尺：
  全长 OAL       43.6 in = 1108 mm = 17.72 u
  枪管（外露）   24 in = 610 mm，Ø 0.33 u = 20.6 mm
  机匣           7.2 × 1.4 in = 2.93 × 0.57 u（含顶部 tang 高 0.72 u）
  管状弹仓       Ø 15 mm = 0.24 u，位于枪管正下方，容量 5 发
  护木           230 mm 长、32 mm 宽 = 3.68 × 0.51 u
  枪托 LOP       13 in = 330 mm；托底 drop heel 75 / toe 194 mm；托底板高 4.8 in = 122 mm

机构几何（两张图交叉量取：用户参考图 = 3D 渲染图；wiki_17.jpg = 真枪棚拍侧视）
--------------------------------------------------------------------------------
标尺：机匣后端 z = +0.42、前端 z = −2.60、机匣底 y = −0.78；1 px = 0.01678 u。

  · **扳机护圈**（trigger guard）＝ 机匣的一部分，**固定不动**，包住扳机。
      原图 x 410…465、y 117…155 → 中心 (y −1.22, z −0.12)，半轴 (z 0.46, y 0.27)，管厚 0.09
      外径 0.92 × 0.54 u = 58 × 34 mm（真枪 ≈ 2.3 × 1.3 in ✓）
  · **杠杆环**（lever loop）＝ 可动件，手指勾的地方，横向拉长的椭圆。
      原图 x 325…425、y 155…192 → 中心 (y −1.85, z +0.92)，半轴 (z 0.84, y 0.32)，管厚 0.11
      外径 1.68 × 0.64 u = 105 × 40 mm（真枪 ≈ 4.2 × 1.6 in ✓）
      ⚠ 真枪是**两个环**：护圈在前（小、包扳机、固定），杠杆环在后下方（大、可动），
        关闭时上下相接，侧面看成"8"字 —— 只做一个环是不对的。
  · **杠杆**转轴在机匣**前下方** pivot (y −0.95, z −2.30)；杆贴机匣底向后到 z ≈ −0.55，
      再下斜到环前端。环在转轴**后方**（Δz > 0）⇒ 打开是绕 X 轴**正角度**、环向前下方摆。
      全开 55°：环位移 ≈ 193 mm，闭锁块行程 1.5 in = 38 mm ⇒ 增益 ≈ 5:1（与真枪手感同量级）。
  · **装填门**原图 x 482…527 → z −1.63…−0.88（机匣中后部），在机匣右壁 x = +0.29 的开口里。
  · **抛壳口**在机匣右壁上部 z −1.85…−0.72。
  · **倍镜**：M1894 顶抛壳，弹壳从机匣顶上向右上飞出 ⇒ 镜子必须架够高。本模型镜管中心
      高于 bore **0.80 u = 50 mm**，镜管底与机匣顶之间留 0.435 u ≈ 27 mm 抛壳净空。

契约（Java 侧按名字取，改名即崩）
----------------------------------
  骨骼见 CONTRACT_BONES（Win94ItemRenderer 还硬编码 "move" / "lever"）；
  动画见 CONTRACT_ANIMS（Win94Item 的 clip 表 + tick 契约 ceil(length × 20)）。
"""

