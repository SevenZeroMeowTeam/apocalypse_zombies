package com.apocalypse.zombies.entity.ai;

/**
 * 「看得见就能打」的自选标记 —— 给**远程**怪用的。
 *
 * <p>{@link PreyJudge} 的默认判据是「走得到」：近战怪打不着的东西，锁上只会站着发呆，
 * 所以视线不算数。远程怪不一样 —— 弓 / 枪 / 骨矢只要视线通、距离在射程内就能打，
 * 柱顶、塔上、船上的目标对它来说是<b>该打</b>的，不是该放弃的。实测：3 格石柱顶上的
 * 靶子对射手是「看得见、走不到」，不加这条它会 45 秒一箭不放（目标表被空转占死）。</p>
 *
 * <p><b>为什么让实体自己声明，而不是按类名或 goal 猜：</b>这样放宽的爆炸半径精确等于
 * 「谁实现了谁才算」—— 本模组的近战怪一个都不受影响，也不会因为别的模组往射手身上
 * 加了个什么 goal 就误判。判序见 {@link PreyJudge#usable}：贴脸 → 看得见就能打 → 走得到，
 * 前两条任一成立即可。</p>
 */
public interface SightFiring {

    /**
     * 「看得见就能打」的距离上限（格）。应当取自己**最远那件武器**的射程：
     * 报小了会对着够得着的目标发呆（退回死锁），报大了会锁上一个真打不到的目标。
     *
     * @return ≤ 0 表示不启用这条判据（等同于没实现本接口）
     */
    double sightFiringRange();
}
